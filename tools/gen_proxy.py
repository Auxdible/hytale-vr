"""Generates the opengl32.dll proxy export files from tools/opengl32_exports.txt.

Every export forwards to the real System32 opengl32.dll through a jump table,
except the ones in OVERRIDES, which src/proxy implements in C++.

Run: python tools/gen_proxy.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "proxy" / "generated"

# Exports implemented in C++ as hvr_<name>.
OVERRIDES = {
    "wglGetProcAddress",
    "wglSwapBuffers",
    "glClear",
    "glViewport",
    "glDrawArrays",
    "glDrawElements",
    "glBindTexture",
    "glDrawBuffer",
    "glReadBuffer",
}

HEADER = "Generated by tools/gen_proxy.py. Do not edit."


def main():
    names = [n.strip() for n in (ROOT / "tools" / "opengl32_exports.txt").read_text().splitlines() if n.strip()]
    missing = OVERRIDES - set(names)
    if missing:
        raise SystemExit(f"overrides not in export list: {sorted(missing)}")
    forwarded = [n for n in names if n not in OVERRIDES]
    OUT.mkdir(parents=True, exist_ok=True)

    lines = ["; " + HEADER, "EXTERN hvr_real_exports:QWORD", "", ".code", ""]
    for index, name in enumerate(forwarded):
        lines += [f"hvr_x_{name} PROC", f"    jmp QWORD PTR [hvr_real_exports + {index * 8}]", f"hvr_x_{name} ENDP", ""]
    lines.append("END")
    (OUT / "stubs.asm").write_text("\n".join(lines) + "\n")

    lines = ["; " + HEADER, "LIBRARY opengl32", "EXPORTS"]
    for name in names:
        target = f"hvr_{name}" if name in OVERRIDES else f"hvr_x_{name}"
        lines.append(f"    {name} = {target}")
    (OUT / "opengl32.def").write_text("\n".join(lines) + "\n")

    lines = ["// " + HEADER, "#pragma once", "", f"constexpr int kForwardedExportCount = {len(forwarded)};",
             "constexpr const char* kForwardedExportNames[kForwardedExportCount] = {"]
    lines += [f'    "{name}",' for name in forwarded]
    lines += ["};", "", f"constexpr int kTotalExportCount = {len(names)};"]
    (OUT / "export_names.inc").write_text("\n".join(lines) + "\n")
    print(f"{len(names)} exports, {len(forwarded)} forwarded, {len(OVERRIDES)} implemented")


if __name__ == "__main__":
    main()
